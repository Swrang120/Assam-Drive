create table if not exists public.ride_status_history(
 id bigint generated by default as identity primary key,
 ride_id bigint not null references public.rides(id) on delete cascade,
 status text not null,
 actor_id uuid references auth.users(id),
 created_at timestamptz not null default now()
);

create table if not exists public.ride_otp(
 ride_id bigint primary key references public.rides(id) on delete cascade,
 otp_hash text not null,
 attempts integer not null default 0,
 expires_at timestamptz not null,
 verified_at timestamptz
);

create table if not exists public.ride_location_updates(
 id bigint generated by default as identity primary key,
 ride_id bigint not null references public.rides(id) on delete cascade,
 driver_id uuid not null references public.driver_profiles(id) on delete cascade,
 lat double precision not null,
 lng double precision not null,
 accuracy_m double precision,
 recorded_at timestamptz not null default now()
);

create table if not exists public.payments(
 id bigint generated by default as identity primary key,
 ride_id bigint not null unique references public.rides(id) on delete cascade,
 customer_id uuid not null references public.profiles(id),
 driver_id uuid references public.driver_profiles(id),
 amount numeric(12,2) not null,
 method text not null check(method in('CASH','UPI','ONLINE')),
 status text not null default 'PENDING' check(status in('PENDING','PROCESSING','PAID','FAILED','REFUNDED')),
 provider_reference text,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);

create table if not exists public.driver_earnings(
 id bigint generated by default as identity primary key,
 driver_id uuid not null references public.driver_profiles(id) on delete cascade,
 ride_id bigint not null unique references public.rides(id) on delete cascade,
 gross_amount numeric(12,2) not null,
 platform_commission numeric(12,2) not null default 0,
 net_amount numeric(12,2) not null,
 created_at timestamptz not null default now()
);

create table if not exists public.ratings(
 id bigint generated by default as identity primary key,
 ride_id bigint not null references public.rides(id) on delete cascade,
 from_user_id uuid not null references auth.users(id),
 to_user_id uuid not null references auth.users(id),
 stars integer not null check(stars between 1 and 5),
 comment text,
 created_at timestamptz not null default now(),
