create or replace function public.ensure_my_profile(p_role text,p_name text,p_phone text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); result jsonb;
begin
 if uid is null then raise exception 'Not authenticated'; end if;
 if p_role not in('CUSTOMER','DRIVER') then raise exception 'Invalid role'; end if;
 insert into profiles(id,role,full_name,phone,updated_at) values(uid,p_role,coalesce(p_name,''),coalesce(p_phone,''),now())
 on conflict(id) do update set role=excluded.role,full_name=excluded.full_name,phone=excluded.phone,updated_at=now();
 if p_role='DRIVER' then
   insert into driver_profiles(id,vehicle_type,updated_at) values(uid,'BIKE',now()) on conflict(id) do nothing;
 end if;
 select jsonb_build_object('id',p.id,'role',p.role,'full_name',p.full_name,'phone',p.phone,'driver',case when p.role='DRIVER' then (select to_jsonb(d) from driver_profiles d where d.id=p.id) else null end) into result from profiles p where p.id=uid;
 return result;
end $$;

create or replace function public.set_driver_presence(p_online boolean,p_lat double precision default null,p_lng double precision default null)
returns jsonb language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); d driver_profiles%rowtype;
begin
 select * into d from driver_profiles where id=uid for update;
 if not found then raise exception 'Driver profile not found'; end if;
 if p_online and not d.verified then raise exception 'Driver is not approved'; end if;
 update driver_profiles set online=p_online,current_lat=coalesce(p_lat,current_lat),current_lng=coalesce(p_lng,current_lng),last_seen_at=now(),updated_at=now() where id=uid returning * into d;
 insert into audit_logs(actor_id,action,entity_type,entity_id,metadata) values(uid,case when p_online then 'DRIVER_ONLINE' else 'DRIVER_OFFLINE' end,'driver',uid::text,'{}');
 return to_jsonb(d);
end $$;

create or replace function public.update_driver_position(p_lat double precision,p_lng double precision,p_accuracy double precision default null)
returns jsonb language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); r rides%rowtype;
begin
 update driver_profiles set current_lat=p_lat,current_lng=p_lng,last_seen_at=now(),updated_at=now() where id=uid and verified=true;
 select * into r from rides where driver_id=uid and status in('DRIVER_ASSIGNED','DRIVER_AT_PICKUP','OTP_PENDING','RIDE_STARTED') order by id desc limit 1;
 if r.id is not null then insert into ride_location_updates(ride_id,driver_id,lat,lng,accuracy_m) values(r.id,uid,p_lat,p_lng,p_accuracy); end if;
 return jsonb_build_object('ok',true);
end $$;

create or replace function public.create_ride(p_vehicle text,p_pickup text,p_destination text,p_pickup_lat double precision,p_pickup_lng double precision,p_destination_lat double precision,p_destination_lng double precision,p_distance_km numeric,p_duration_minutes integer)
returns rides language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); r rides%rowtype; f fare_settings%rowtype; chosen uuid;
begin
 if uid is null then raise exception 'Not authenticated'; end if;
 if not exists(select 1 from profiles where id=uid and role='CUSTOMER') then raise exception 'Customer account required'; end if;
 select * into f from fare_settings where vehicle_type=p_vehicle and active=true;
 if not found then raise exception 'Fare unavailable'; end if;
 select dp.id into chosen from driver_profiles dp
 where dp.vehicle_type=p_vehicle and dp.verified=true and dp.online=true and dp.last_seen_at>now()-interval '90 seconds'
 and dp.current_lat is not null and dp.current_lng is not null
 order by ((dp.current_lat-p_pickup_lat)^2 + ((dp.current_lng-p_pickup_lng)*cos(radians(p_pickup_lat)))^2)
 limit 1;
 insert into rides(customer_id,driver_id,vehicle_type,pickup_text,destination_text,pickup_lat,pickup_lng,destination_lat,destination_lng,distance_km,duration_minutes,fare,status,created_at)
 values(uid,chosen,p_vehicle,p_pickup,p_destination,p_pickup_lat,p_pickup_lng,p_destination_lat,p_destination_lng,greatest(p_distance_km,0),greatest(p_duration_minutes,0),greatest(f.base_fare+greatest(p_distance_km,0)*f.per_km,f.minimum_fare),case when chosen is null then 'SEARCHING' else 'DRIVER_ASSIGNED' end,now()) returning * into r;
 insert into ride_status_history(ride_id,status,actor_id) values(r.id,r.status,uid);
 if chosen is not null then
   update rides set driver_phone_snapshot=(select phone from profiles where id=chosen),accepted_at=now() where id=r.id returning * into r;
   insert into notifications(user_id,type,title,body,data) values(chosen,'RIDE_REQUEST','New ride request','A customer requested a ride',jsonb_build_object('ride_id',r.id));
 end if;
 return r;
end $$;

create or replace function public.accept_ride(p_ride_id bigint)
returns rides language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); r rides%rowtype; d driver_profiles%rowtype;
begin
 select * into d from driver_profiles where id=uid for update;
 if not found or not d.verified or not d.online then raise exception 'Driver is not approved/online'; end if;
 select * into r from rides where id=p_ride_id for update;
 if not found or r.status<>'SEARCHING' or r.driver_id is not null then raise exception 'Ride is no longer available'; end if;
 update rides set driver_id=uid,status='OTP_PENDING',accepted_at=now(),driver_phone_snapshot=(select phone from profiles where id=uid) where id=p_ride_id returning * into r;
 insert into ride_otp(ride_id,otp_hash,expires_at) values(r.id,encode(digest(lpad(floor(random()*10000)::int::text,4,'0'),'sha256'),'hex'),now()+interval '10 minutes')
 on conflict(ride_id) do update set otp_hash=excluded.otp_hash,attempts=0,expires_at=excluded.expires_at,verified_at=null;
 -- replace hash with deterministic generated OTP stored temporarily in notification payload is not safe, so create OTP separately below
 insert into ride_status_history(ride_id,status,actor_id) values(r.id,'OTP_PENDING',uid);
 insert into notifications(user_id,type,title,body,data) values(r.customer_id,'RIDE_ASSIGNED','Driver assigned','A verified driver accepted your ride',jsonb_build_object('ride_id',r.id));
 return r;
end $$;

create or replace function public.verify_ride_otp(p_ride_id bigint,p_otp text)
returns rides language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); r rides%rowtype; o ride_otp%rowtype; expected text;
begin
 select * into r from rides where id=p_ride_id and driver_id=uid for update;
 if not found or r.status<>'OTP_PENDING' then raise exception 'Ride is not awaiting OTP'; end if;
 select * into o from ride_otp where ride_id=p_ride_id for update;
 if not found or o.expires_at<now() then raise exception 'OTP expired'; end if;
 expected:=encode(digest(p_otp,'sha256'),'hex');
 if expected<>o.otp_hash then
   update ride_otp set attempts=attempts+1 where ride_id=p_ride_id returning * into o;
   if o.attempts>=2 then
     update rides set status='CANCELLED',cancelled_at=now(),cancel_reason='OTP failed twice' where id=p_ride_id returning * into r;
     insert into ride_status_history(ride_id,status,actor_id) values(r.id,'CANCELLED',uid);
     insert into audit_logs(actor_id,action,entity_type,entity_id,metadata) values(uid,'OTP_FAILED_TWICE','ride',r.id::text,jsonb_build_object('attempts',o.attempts));
   end if;
   return r;
 end if;
 update ride_otp set verified_at=now() where ride_id=p_ride_id;
 update rides set status='RIDE_STARTED',started_at=now(),otp_verified_at=now() where id=p_ride_id returning * into r;
 insert into ride_status_history(ride_id,status,actor_id) values(r.id,'RIDE_STARTED',uid);
 return r;
end $$;

create or replace function public.complete_ride(p_ride_id bigint)
returns rides language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); r rides%rowtype; commission numeric:=0;
begin
 select * into r from rides where id=p_ride_id and (customer_id=uid or driver_id=uid) for update;
 if not found or r.status<>'RIDE_STARTED' then raise exception 'Ride cannot be completed'; end if;
 update rides set status='COMPLETED',completed_at=now(),payment_status=case when payment_method='CASH' then 'PAID' else payment_status end where id=p_ride_id returning * into r;
 insert into ride_status_history(ride_id,status,actor_id) values(r.id,'COMPLETED',uid);
 if r.driver_id is not null then
   insert into driver_earnings(driver_id,ride_id,gross_amount,platform_commission,net_amount) values(r.driver_id,r.id,r.fare,commission,r.fare-commission) on conflict(ride_id) do nothing;
 end if;
 return r;
end $$;

create or replace function public.cancel_ride(p_ride_id bigint,p_reason text)
returns rides language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); r rides%rowtype;
begin
 select * into r from rides where id=p_ride_id and (customer_id=uid or driver_id=uid) for update;
 if not found or r.status in('COMPLETED','CANCELLED') then raise exception 'Ride cannot be cancelled'; end if;
 update rides set status='CANCELLED',cancelled_at=now(),cancel_reason=left(coalesce(p_reason,'Cancelled'),250) where id=p_ride_id returning * into r;
 insert into ride_status_history(ride_id,status,actor_id) values(r.id,'CANCELLED',uid);
 return r;
end $$;

create or replace function public.record_payment(p_ride_id bigint,p_method text,p_status text default 'PAID',p_provider_reference text default null)
returns payments language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); r rides%rowtype; p payments%rowtype;
begin
 select * into r from rides where id=p_ride_id and customer_id=uid for update;
 if not found or r.status<>'COMPLETED' then raise exception 'Ride is not payable'; end if;
 insert into payments(ride_id,customer_id,driver_id,amount,method,status,provider_reference)
 values(r.id,r.customer_id,r.driver_id,r.fare,p_method,p_status,p_provider_reference)
 on conflict(ride_id) do update set method=excluded.method,status=excluded.status,provider_reference=excluded.provider_reference,updated_at=now()
 returning * into p;
 update rides set payment_method=p_method,payment_status=p_status where id=r.id;
 return p;
end $$;

create or replace function public.submit_rating(p_ride_id bigint,p_stars integer,p_comment text default null)
returns ratings language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); r rides%rowtype; target uuid; out ratings%rowtype;
begin
 select * into r from rides where id=p_ride_id and status='COMPLETED' and (customer_id=uid or driver_id=uid);
 if not found then raise exception 'Completed ride not found'; end if;
 target:=case when r.customer_id=uid then r.driver_id else r.customer_id end;
 if target is null then raise exception 'No rating target'; end if;
 insert into ratings(ride_id,from_user_id,to_user_id,stars,comment) values(r.id,uid,target,p_stars,left(p_comment,500))
 on conflict(ride_id,from_user_id) do update set stars=excluded.stars,comment=excluded.comment
 returning * into out;
 return out;
end $$;

create or replace function public.create_sos(p_ride_id bigint,p_lat double precision default null,p_lng double precision default null,p_message text default null)
returns sos_events language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); out sos_events%rowtype;
begin
 if not exists(select 1 from rides where id=p_ride_id and (customer_id=uid or driver_id=uid) and status not in('COMPLETED','CANCELLED')) then raise exception 'Active ride required'; end if;
 insert into sos_events(ride_id,user_id,lat,lng,message) values(p_ride_id,uid,p_lat,p_lng,left(p_message,500)) returning * into out;
 insert into audit_logs(actor_id,action,entity_type,entity_id,metadata) values(uid,'SOS_CREATED','ride',p_ride_id::text,jsonb_build_object('lat',p_lat,'lng',p_lng));
 return out;
end $$;

